export type TextKey = keyof typeof en;
const dictionaries: Record<Language, Record<TextKey, string>> = { en, ar };
export function translator(language: Language) {
  const messages = dictionaries[language] || en;
  return (key: TextKey, values: Record<string, string | number> = {}) =>
    messages[key].replace(/\{(\w+)\}/g, (_, name) =>
      typeof values[name] === "number"
        ? new Intl.NumberFormat(language).format(values[name])
        : String(values[name] ?? `{${name}}`),
    );
}

export function localizeError(value: unknown, language: Language) {
  const t = translator(language);
  const text =
    value instanceof Error
      ? value.message
      : typeof value === "string"
        ? value
        : t("genericError");
  if (language === "en") return text;
  const direct = (Object.keys(en) as TextKey[]).find((key) => en[key] === text);
  if (direct) return t(direct);
  if (/valid YouTube URL|No valid video or playlist/.test(text))
    return t("validURL");
  if (/Loading details took too long/.test(text)) return t("timeout");
  if (/requires FFmpeg|Install ffmpeg/.test(text)) return t("encoderNeeded");
  if (/not ready to open/.test(text)) return t("fileNotReady");
  if (/moved or deleted/.test(text)) return t("fileMissing");
  const status = text.match(/HTTP (\d+)/);
  if (status) return t("rejected", { status: status[1] });
  const fallback = text.match(
    /Could not download (.+?); saved the best working alternative at (.+)\./,
  );
  if (fallback)
    return t("fallback", { requested: fallback[1], actual: fallback[2] });
  return text;
}
